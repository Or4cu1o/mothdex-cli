#!/usr/bin/env bash
# The licence notices of the Go modules linked into the release binaries (BSD, MIT and Apache-2.0 ask for the text to travel with
# a binary). One file per binary, built from the exact module list of that binary: the modules `go list -deps` reports for the
# targets the release builds, with the full text of every licence file at the root of each module (LICENSE, COPYING, NOTICE,
# PATENTS and the like), read from the module cache at the version pinned in go.mod.
#
#   scripts/gen-go-notices.sh           rewrite THIRD_PARTY/go-modules-mothdex.txt and go-modules-mothdex-gui.txt
#   scripts/gen-go-notices.sh --check   fail when either file differs from what go.mod and the code give now (CI)
#
# A module without a licence file fails the run: a binary must not link a module that has no notice. scripts/verify-dist.sh
# checks the other way round on the real binaries (`go version -m` of each built binary against the file in its archive).
set -euo pipefail

cd "$(dirname "$0")/.."
export LC_ALL=C CGO_ENABLED=0 GOFLAGS=-mod=readonly

mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

fail() { echo "gen-go-notices: $*" >&2; exit 1; }

# The modules of one binary over every OS the release builds it for: "<path> <version> <dir>" lines, sorted.
module_list() { # package tags goos...
  local pkg=$1 tags=$2 goos
  shift 2
  for goos in "$@"; do
    GOOS=$goos GOARCH=amd64 go list -tags "$tags" -deps \
      -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' "$pkg"
  done | sort -u
}

# The licence files at the root of a module, by name, in a fixed order.
licence_files() { # dir
  local f
  for f in "$1"/*; do
    [ -f "$f" ] || continue
    case "$(basename "$f" | tr '[:upper:]' '[:lower:]')" in
      licen[cs]e | licen[cs]e.* | copying | copying.* | notice | notice.* | patents | unlicense | unlicense.*) printf '%s\n' "$f" ;;
    esac
  done | sort
}

render() { # title package tags goos...
  local title=$1 pkg=$2 tags=$3 path version dir f count=0 list
  shift 3
  list=$(module_list "$pkg" "$tags" "$@")
  [ -n "$list" ] || fail "no modules found for $pkg"
  cat <<EOF
Licence notices of the Go modules linked into $title.
Generated by scripts/gen-go-notices.sh from the module list of the release build (go list -deps; go.mod pins the versions).
Do not edit by hand. The licence of this program itself is the LICENSE file at the root of the archive.
EOF
  while read -r path version dir; do
    [ -n "$path" ] || continue
    # an empty Dir (the module is not in the cache) must not turn the licence glob into a glob of the current folder or of /
    [ -n "$dir" ] && [ -d "$dir" ] || fail "module $path $version has no directory in the module cache (run go mod download)"
    mapfile -t files < <(licence_files "$dir")
    [ "${#files[@]}" -gt 0 ] || fail "module $path $version has no licence file (it is linked into $title and needs a notice)"
    printf '\n================================================================================\nModule: %s %s\n================================================================================\n' "$path" "$version"
    for f in "${files[@]}"; do
      printf '\n--- %s ---\n\n' "$(basename "$f")"
      cat "$f"
      [ -z "$(tail -c1 "$f")" ] || printf '\n'
    done
    count=$((count + 1))
  done <<<"$list"
  [ "$count" -gt 0 ] || fail "no module was written for $title"
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

status=0
for out in THIRD_PARTY/go-modules-mothdex.txt THIRD_PARTY/go-modules-mothdex-gui.txt; do
  case "$out" in
    */go-modules-mothdex.txt) render "mothdex (the CLI)" ./cmd/mothdex "" linux windows darwin >"$tmp/new" ;;
    *) render "mothdex-gui (the GUI)" ./cmd/mothdex-gui gui linux windows >"$tmp/new" ;;
  esac
  if [ "$mode" = write ]; then
    cp "$tmp/new" "$out"
    echo "gen-go-notices: wrote $out ($(grep -c '^Module: ' "$out") modules)"
  elif cmp -s "$tmp/new" "$out"; then
    echo "gen-go-notices: $out is current ($(grep -c '^Module: ' "$out") modules)"
  else
    echo "gen-go-notices: $out is not what go.mod and the code give now; run scripts/gen-go-notices.sh and commit it:" >&2
    diff <(grep '^Module: ' "$out" 2>/dev/null || true) <(grep '^Module: ' "$tmp/new") >&2 || true
    status=1
  fi
done
exit "$status"
